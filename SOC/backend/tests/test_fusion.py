    def test_phase5_incident_anchors_and_reevaluation(self):
        """
        WP-1E Phase 5: Verify that when two detection events originate from the same source_event_id
        (e.g., from different detector_versions during re-evaluation), they map to the same incident_anchor
        and attach as evidence to the existing incident rather than creating duplicate incidents.
        """
        # Event 1: generated by detector version 1.0.0
        self._insert_event("e1", "2026-10-03T10:00:00Z", "host1", "LOW", "10.0.0.1", source_event_id="src-common-100", detector_version="1.0.0")
        with get_db_connection() as conn:
            engine = EvidenceFusionEngine(conn)
            engine.process_event("e1")
            conn.commit()

            cursor = conn.execute("SELECT * FROM incidents")
            incidents = cursor.fetchall()
            self.assertEqual(len(incidents), 1)
            incident_id = incidents[0]["incident_id"]

            # Verify anchor was recorded
            cursor = conn.execute("SELECT * FROM incident_anchors WHERE agent_id = 'agent-1' AND source_event_id = 'src-common-100'")
            anchors = cursor.fetchall()
            self.assertEqual(len(anchors), 1)
            self.assertEqual(anchors[0]["incident_id"], incident_id)

        # Event 2: re-evaluated with detector version 2.0.0 (different detection_event_id, same source_event_id, higher severity)
        self._insert_event("e2", "2026-10-03T10:00:00Z", "host1", "CRITICAL", "10.0.0.1", source_event_id="src-common-100", detector_version="2.0.0")
        with get_db_connection() as conn:
            engine = EvidenceFusionEngine(conn)
            engine.process_event("e2")
            conn.commit()

            # Must still have exactly 1 incident (no duplicate created)
            cursor = conn.execute("SELECT * FROM incidents")
            incidents = cursor.fetchall()
            self.assertEqual(len(incidents), 1)
            self.assertEqual(incidents[0]["incident_id"], incident_id)
            self.assertEqual(incidents[0]["max_severity"], "CRITICAL")

            # Both detection events should be attached as evidence to the same incident
            cursor = conn.execute("SELECT detection_event_id, classification FROM incident_evidence WHERE incident_id = ?", (incident_id,))
            ev_map = {row["detection_event_id"]: row["classification"] for row in cursor.fetchall()}
            self.assertEqual(set(ev_map.keys()), {"e1", "e2"})
            self.assertEqual(ev_map["e1"], "PRIMARY_DETECTION")
            self.assertEqual(ev_map["e2"], "HISTORICAL_RE_EVALUATION")

            # Check events table classification as well
            cur_ev = conn.execute("SELECT detection_event_id, classification FROM events WHERE detection_event_id IN ('e1', 'e2')")
            event_classes = {row["detection_event_id"]: row["classification"] for row in cur_ev.fetchall()}
            self.assertEqual(event_classes.get("e2"), "HISTORICAL_RE_EVALUATION")

    def test_phase5_concurrent_anchor_creation_eliminates_duplicate_incidents(self):
        """
        WP-1E Phase 5: Verify that when two concurrent workers ingest detections for the same
        (agent_id, source_event_id), SQLite transactions/savepoints prevent duplicate incident rows.
        """
        import threading
        self._insert_event("c1", "2026-10-03T10:00:00Z", "host1", "LOW", "10.0.0.1", source_event_id="src-race-999", detector_version="1.0.0")
        self._insert_event("c2", "2026-10-03T10:00:00Z", "host1", "HIGH", "10.0.0.1", source_event_id="src-race-999", detector_version="2.0.0")

        errors = []
        def worker_task(ev_id):
            try:
                with get_db_connection() as conn:
                    engine = EvidenceFusionEngine(conn)
                    engine.process_event(ev_id)
                    conn.commit()
            except Exception as ex:
                errors.append(ex)

        t1 = threading.Thread(target=worker_task, args=("c1",))
        t2 = threading.Thread(target=worker_task, args=("c2",))
        t1.start()
        t2.start()
        t1.join()
        t2.join()

        self.assertEqual(len(errors), 0, f"Concurrent workers raised errors: {errors}")

        with get_db_connection() as conn:
            # Must have exactly 1 incident (zero duplicate incident rows)
            cursor = conn.execute("SELECT * FROM incidents")
            incidents = cursor.fetchall()
            self.assertEqual(len(incidents), 1)

            # Exactly 1 anchor row
            cursor = conn.execute("SELECT * FROM incident_anchors WHERE agent_id = 'agent-1' AND source_event_id = 'src-race-999'")
            anchors = cursor.fetchall()
            self.assertEqual(len(anchors), 1)

            # Both events linked to the same single incident
            cursor = conn.execute("SELECT detection_event_id FROM incident_evidence WHERE incident_id = ?", (incidents[0]["incident_id"],))
            linked_ids = {row["detection_event_id"] for row in cursor.fetchall()}
            self.assertEqual(linked_ids, {"c1", "c2"})

    def test_phase5_missing_source_event_id_fallback(self):
        """
        WP-1E Phase 5: When source_event_id is None or empty, incident fusion proceeds
        normally using hostname/IP correlation without touching incident_anchors.
        """
        self._insert_event("m1", "2026-10-03T10:00:00Z", "host_missing", "LOW", "10.10.10.1", source_event_id=None)
        with get_db_connection() as conn:
            # Overwrite source_event_id to None in the event payload
            cur = conn.execute("SELECT data FROM events WHERE detection_event_id = 'm1'")
            d = json.loads(cur.fetchone()["data"])
            d["source_event_id"] = None
            conn.execute("UPDATE events SET data = ? WHERE detection_event_id = 'm1'", (json.dumps(d),))
            conn.commit()

            engine = EvidenceFusionEngine(conn)
            engine.process_event("m1")
            conn.commit()

            cursor = conn.execute("SELECT * FROM incidents")
            incidents = cursor.fetchall()
            self.assertEqual(len(incidents), 1)

            # incident_anchors must be empty
            cursor = conn.execute("SELECT * FROM incident_anchors")
            self.assertEqual(len(cursor.fetchall()), 0)

