    def _insert_event(self, event_id: str, timestamp: str, hostname: str, severity: str, source_ip: str = None, username: str = None, quarantine_status: str = 'ACTIVE_VERIFIED', source_event_id: str = None, detector_version: str = "1.0.0"):
        with get_db_connection() as conn:
            data = {
                "detection_event_id": event_id,
                "timestamp": timestamp,
                "agent_id": "agent-1",
                "hostname": hostname,
                "os": "Windows",
                "source_event_id": source_event_id or f"src-{event_id}",
                "detection_type": "test_rule",
                "confidence": 1.0,
                "severity": severity,
                "detector_name": "test_detector",
                "detector_version": detector_version,
                "evidence": {}
            }
            if source_ip:
                data["evidence"]["source_ip"] = source_ip
            if username:
                data["evidence"]["username"] = username

            conn.execute("INSERT INTO events (detection_event_id, data, quarantine_status) VALUES (?, ?, ?)", (event_id, json.dumps(data), quarantine_status))
            conn.execute("INSERT INTO fusion_event_state (detection_event_id, status, updated_at) VALUES (?, 'PENDING', CURRENT_TIMESTAMP)", (event_id,))
            conn.commit()

